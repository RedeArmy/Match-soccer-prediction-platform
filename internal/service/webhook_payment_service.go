// WebhookPaymentService processes confirmed payment notifications from
// external payment providers and credits the user's balance.
//
// Recurrente carries the user ID in its payload metadata; the service trusts
// the signature-verified value directly.
//
// PayPal uses an opaque payment intent token (custom_id) generated by the
// server before the PayPal order is created. The service resolves the token
// to the associated user and amount, preventing a user from substituting
// another user's ID. Idempotency is enforced by the unique constraint on
// payment_intents.capture_id: a given PayPal capture can credit at most one
// intent, and a given intent can only be captured once.
type WebhookPaymentService interface {
	// CreditFromRecurrente credits amountCents to userID's balance following a
	// confirmed Recurrente transaction. reference is the provider's transaction
	// ID, stored in the audit log for traceability.
	CreditFromRecurrente(ctx context.Context, userID, amountCents int, currency, reference string) error
	// ResolveAndCreditPayPalIntent resolves intentToken to a pending, non-expired
	// payment intent, atomically captures it, and credits the user's balance.
	// webhookAmountCents is the amount declared in the PayPal payload; if > 0 and
	// it differs from the server-authoritative intent amount, a warning is logged
	// (the intent amount is always used for the actual credit).
	// Returns nil for idempotent duplicate webhook deliveries (same captureID).
	// Returns apperrors.NotFound when the token is unknown or expired.
	// Returns apperrors.Conflict when the intent is captured by a different captureID.
	ResolveAndCreditPayPalIntent(ctx context.Context, intentToken, captureID string, webhookAmountCents int) error
}

type webhookPaymentService struct {
	ledgerRepo repository.BalanceLedgerRepository
	intentRepo repository.PaymentIntentRepository
	userRepo   repository.UserRepository // wired via SetUserRepository; used to read balance_currency
	kycGate    KYCGate                   // wired via SetKYCGate after construction; nil disables KYC checks
	fxSvc      ExchangeRateService       // wired via SetExchangeRateService; used for GTQ-balance PayPal users
	audit      AuditLogger
	log        *zap.Logger
}

// NewWebhookPaymentService constructs a WebhookPaymentService.
func NewWebhookPaymentService(
	ledgerRepo repository.BalanceLedgerRepository,
	intentRepo repository.PaymentIntentRepository,
	audit AuditLogger,
	log *zap.Logger,
) WebhookPaymentService {
	return &webhookPaymentService{
		ledgerRepo: ledgerRepo,
		intentRepo: intentRepo,
		audit:      audit,
		log:        log,
	}
}

// SetKYCGate wires the KYCGate into the service for deposit and AML checks.
// Called once at startup after the KYC module is initialised. When nil,
// CheckDeposit and AML flagging are skipped (safe for tests without a DB).
func (s *webhookPaymentService) SetKYCGate(gate KYCGate) { s.kycGate = gate }

// SetExchangeRateService wires the exchange-rate service used when a GTQ-balance
// user deposits via PayPal (USD→GTQ conversion). When nil, the raw USD amount
// is credited without conversion (safe for tests without a DB).
func (s *webhookPaymentService) SetExchangeRateService(svc ExchangeRateService) { s.fxSvc = svc }

// SetUserRepository wires the user repository so that the balance_currency can
// be read before deciding whether to convert a PayPal USD deposit.
func (s *webhookPaymentService) SetUserRepository(repo repository.UserRepository) { s.userRepo = repo }

func (s *webhookPaymentService) CreditFromRecurrente(ctx context.Context, userID, amountCents int, currency, reference string) error {
	// Credit the amount in the payment currency directly. For USD deposits the
	// user's balance_currency is set to "USD" atomically by CreditIdempotent, so
	// that all future balance operations (entry fees, prizes) are also USD-based.
	// No GTQ conversion is performed here; display conversion is handled by the
	// frontend using the live exchange rate.
	opts := creditDirectOpts{
		kind:        domain.LedgerKindWebhookRecurrente,
		auditAction: domain.AuditActionWebhookPaymentCredit,
	}
	if currency == "USD" {
		opts.sourceCurrency = "USD"
		opts.sourceAmountCents = amountCents
	}

	if s.kycGate != nil {
		if err := s.kycGate.CheckDeposit(ctx, userID, amountCents); err != nil {
			return err
		}
		if err := s.kycGate.CheckDepositVelocity(ctx, userID, amountCents); err != nil {
			return err
		}
	}
	if err := s.creditDirect(ctx, userID, amountCents, currency, reference, opts); err != nil {
		return err
	}
	// Mark the corresponding payment_intent as captured so the admin panel
	// reflects the correct status. Failure here is non-fatal: the balance
	// was already credited; the intent row will stay 'pending' until it
	// expires, which is acceptable and recoverable.
	if err := s.intentRepo.MarkCapturedByToken(ctx, reference); err != nil {
		s.log.Warn("recurrente webhook: failed to mark intent captured",
			zap.String("reference", reference),
			zap.Error(err),
		)
	}
	s.recordAMLIfNeeded(ctx, userID, amountCents)
	return nil
}

// creditDirectOpts groups the per-call metadata for creditDirect, keeping its
// parameter count within the authorised maximum of 7.
type creditDirectOpts struct {
	kind              domain.BalanceLedgerKind
	auditAction       string
	sourceCurrency    string
	sourceAmountCents int
}

func (s *webhookPaymentService) creditDirect(ctx context.Context, userID, amountCents int, currency, reference string, opts creditDirectOpts) error {
	if amountCents <= 0 {
		return apperrors.Validation("amount_cents must be positive")
	}
	if reference == "" {
		return apperrors.Validation("reference is required for webhook payments")
	}

	// Prefix the reference with the provider kind so that identical transaction
	// IDs from different providers cannot collide in the unique DB index.
	scopedRef := string(opts.kind) + ":" + reference
	credited, err := s.ledgerRepo.CreditIdempotent(ctx, userID, amountCents, opts.kind, scopedRef, opts.sourceCurrency, opts.sourceAmountCents)
	if err != nil {
		return err
	}
	if !credited {
		s.log.Debug("webhook payment: idempotent re-delivery ignored",
			zap.String("reference", scopedRef),
			zap.String("kind", string(opts.kind)),
		)
		return nil
	}

	resType := "user"
	s.audit.Log(ctx, nil, nil, opts.auditAction, &resType, &userID, map[string]any{
		"amount_cents": amountCents,
		"currency":     currency,
		"reference":    scopedRef,
		"kind":         string(opts.kind),
	})
	return nil
}

func (s *webhookPaymentService) ResolveAndCreditPayPalIntent(ctx context.Context, intentToken, captureID string, webhookAmountCents int) error {
	if intentToken == "" {
		return apperrors.Validation("intent token is required")
	}
	if captureID == "" {
		return apperrors.Validation("capture ID is required")
	}

	// Fetch the pending intent once: used for both the KYC gate check and the
	// credit-amount resolution so we avoid a second DB round-trip.
	pending, err := s.fetchPendingAndCheckKYC(ctx, intentToken)
	if err != nil {
		return err
	}

	creditAmountCents, sourceCurrency, sourceAmountCents := s.resolvePayPalCredit(ctx, intentToken, pending)

	intent, err := s.intentRepo.CaptureAndCredit(ctx, intentToken, captureID, creditAmountCents, sourceCurrency, sourceAmountCents)
	if errors.Is(err, repository.ErrPaymentIntentAlreadyCaptured) {
		s.log.Debug("paypal webhook: idempotent re-delivery ignored",
			zap.String("intent_token", intentToken),
			zap.String("capture_id", captureID),
		)
		return nil
	}
	if err != nil {
		return err
	}

	// Cross-check the webhook-declared amount against the server-authoritative
	// intent amount. A mismatch is logged as a warning but does not block the
	// credit: the intent amount is always used and the signature has already
	// been verified by the upstream middleware.
	if webhookAmountCents > 0 && webhookAmountCents != intent.AmountCents {
		s.log.Warn("paypal webhook: declared amount differs from intent amount",
			append([]zap.Field{
				zap.Int("webhook_amount_cents", webhookAmountCents),
				zap.Int("intent_amount_cents", intent.AmountCents),
				zap.String("intent_token", intentToken),
				zap.String("capture_id", captureID),
			}, tracing.LogFields(ctx)...)...)
	}

	resType := "payment_intent"
	intentID := int(intent.ID)
	s.audit.Log(ctx, nil, nil, domain.AuditActionWebhookPaymentCredit, &resType, &intentID, map[string]any{
		"user_id":             intent.UserID,
		"amount_cents":        intent.AmountCents,
		"credit_amount_cents": creditAmountCents,
		"currency":            intent.Currency,
		"capture_id":          captureID,
		"kind":                string(domain.LedgerKindWebhookPayPal),
	})
	s.recordAMLIfNeeded(ctx, intent.UserID, creditAmountCents)
	return nil
}

// resolvePayPalCredit returns the credit amount and optional source denomination
// for a PayPal intent.
//
//   - GTQ-balance users: USD intent amount is converted to GTQ at the buy rate.
//     On conversion failure the raw USD amount is used and a warning is logged.
//   - USD-balance users: USD intent amount is credited directly; source fields
//     are set so the frontend can display the exact deposited amount.
//   - Non-USD intents: intent amount is credited as-is with no source fields.
func (s *webhookPaymentService) resolvePayPalCredit(ctx context.Context, intentToken string, pending *domain.PaymentIntent) (creditCents int, srcCurrency string, srcAmountCents int) {
	if pending == nil {
		return 0, "", 0
	}
	if pending.Currency != "USD" {
		return pending.AmountCents, "", 0
	}

	balCurrency := s.resolveBalanceCurrency(ctx, pending.UserID)
	if balCurrency != "GTQ" || s.fxSvc == nil {
		// USD-balance user: credit USD directly and record source denomination.
		return pending.AmountCents, "USD", pending.AmountCents
	}

	gtq, _, convErr := s.fxSvc.ConvertUSDToGTQ(ctx, int64(pending.AmountCents))
	if convErr != nil {
		s.log.Warn("paypal: USD→GTQ conversion failed, crediting raw amount",
			append([]zap.Field{
				zap.Error(convErr),
				zap.String("intent_token", intentToken),
			}, tracing.LogFields(ctx)...)...)
		return pending.AmountCents, "", 0
	}
	return int(gtq), "", 0
}

// resolveBalanceCurrency returns the user's balance_currency, defaulting to
// "GTQ" when the user repository is not wired or the query returns empty.
func (s *webhookPaymentService) resolveBalanceCurrency(ctx context.Context, userID int) string {
	if s.userRepo == nil {
		return "GTQ"
	}
	bc, _ := s.userRepo.GetBalanceCurrency(ctx, userID)
	if bc == "" {
		return "GTQ"
	}
	return bc
}

// fetchPendingAndCheckKYC fetches the intent for token and, when the intent
// is still pending and kycGate is set, runs CheckDeposit + CheckDepositVelocity.
// Returns the intent (nil when not found) and any gate error.
func (s *webhookPaymentService) fetchPendingAndCheckKYC(ctx context.Context, token string) (*domain.PaymentIntent, error) {
	pending, err := s.intentRepo.GetByToken(ctx, token)
	if err != nil {
		return nil, err
	}
	if pending == nil || pending.Status != domain.PaymentIntentPending {
		return pending, nil
	}
	if s.kycGate == nil {
		return pending, nil
	}
	if err := s.kycGate.CheckDeposit(ctx, pending.UserID, pending.AmountCents); err != nil {
		return nil, err
	}
	if err := s.kycGate.CheckDepositVelocity(ctx, pending.UserID, pending.AmountCents); err != nil {
		return nil, err
	}
	return pending, nil
}

// recordAMLIfNeeded writes AuditActionAMLFlagged when either the single-
// transaction or cumulative rolling-period AML threshold is exceeded.
// Non-blocking: the credit is never reversed; only the audit record is created.
func (s *webhookPaymentService) recordAMLIfNeeded(ctx context.Context, userID, amountCents int) {
	if s.kycGate == nil {
		return
	}
	resType := "user"
	if exceeded, err := s.kycGate.ExceedsAMLThreshold(ctx, amountCents); err == nil && exceeded {
		s.audit.Log(ctx, nil, nil, domain.AuditActionAMLFlagged, &resType, &userID, map[string]any{
			"amount_cents":   amountCents,
			"threshold_type": "single_transaction",
		})
	}
	if exceeded, err := s.kycGate.ExceedsCumulativeAMLThreshold(ctx, userID, amountCents); err == nil && exceeded {
		s.audit.Log(ctx, nil, nil, domain.AuditActionAMLFlagged, &resType, &userID, map[string]any{
			"amount_cents":   amountCents,
			"threshold_type": "cumulative",
		})
	}
}

var _ WebhookPaymentService = (*webhookPaymentService)(nil)
